HEADER_FILL = PatternFill("solid", fgColor="1F4E3D")
HEADER_FONT = Font(color="FFFFFF", bold=True, name="Calibri", size=10)
CELL_FONT = Font(name="Calibri", size=10)
WRAP = Alignment(wrap_text=True, vertical="top")
WARN_FILL = PatternFill("solid", fgColor="FFF2CC")
BAD_FILL = PatternFill("solid", fgColor="F8CBAD")


def _style_header(ws: Worksheet, headers: list[str]) -> None:
    ws.append(headers)
    for col, _title in enumerate(headers, start=1):
        cell = ws.cell(1, col)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center")
        ws.column_dimensions[get_column_letter(col)].width = min(28, max(14, len(_title) + 4))
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}1"
    ws.row_dimensions[1].height = 30


def _append_rows(ws: Worksheet, rows: list[list[object]], warn_rows: set[int] | None = None) -> None:
    warn_rows = warn_rows or set()
    for index, row in enumerate(rows, start=2):
        ws.append(row)
        fill = WARN_FILL if index in warn_rows else None
        for col in range(1, len(row) + 1):
            cell = ws.cell(index, col)
            cell.font = CELL_FONT
            cell.alignment = WRAP
            if fill is not None:
                cell.fill = fill
        ws.row_dimensions[index].height = 36
    last_col = get_column_letter(ws.max_column)
    ws.auto_filter.ref = f"A1:{last_col}{ws.max_row}"


def _mark_bad(ws: Worksheet, row: int, cols: list[int]) -> None:
    for col in cols:
        ws.cell(row, col).fill = BAD_FILL


